export interface DepthModules {
  eiModule: string
  snModule: string
  tfModule: string
  pjModule: string
}

/** 把一段素材收成一句：去掉尾部多余标点，补一个句号，不产生「——。」这种接缝 */
function closeSentence(text: string): string {
  const t = text.trim().replace(/[。．.；;]+$/g, '').replace(/[—－]+$/g, '')
  return /[！？!?]$/.test(t) ? t : `${t}。`
}

/**
 * 用代表人物生平生成「四条建议」。
 *
 * 前两条使用生平原文的不同段落，后两条使用结构化的关键抉择与代价，
 * 四条都以「给你的建议：」收尾；每型的维度落点句各不相同（见 depth-lenses.ts）。
 */
export function getLifeAdviceModules(code: string): DepthModules {
  const person = FEATURED_PROFILES[code]
  const pack = LIFE_ADVICE[code]
  const lens = DEPTH_LENSES[code] || FALLBACK_LENS
  if (!person || !pack) {
    return {
      eiModule: `${lens.ei}给你的建议：先补齐这一型的代表人物与素材。`,
      snModule: `${lens.sn}给你的建议：先补齐这一型的代表人物与素材。`,
      tfModule: `${lens.tf}给你的建议：先补齐这一型的代表人物与素材。`,
      pjModule: `${lens.pj}给你的建议：先补齐这一型的代表人物与素材。`,
    }
  }

  // 生平按句切分：优先句号/问叹号，其次分号；仍只有一段时按逗号从中间断开，
  // 保证「起点与志向」与「看世界的角度」两条解析各自拿到不同的素材。
  let sentences = person.story
    .split(/[。！？；]/)
    .map((s) => s.trim())
    .filter(Boolean)
  if (sentences.length < 2) {
    const parts = person.story
      .split(/，/)
      .map((s) => s.trim())
      .filter(Boolean)
    if (parts.length >= 2) {
      const mid = Math.ceil(parts.length / 2)
      sentences = [parts.slice(0, mid).join('，'), parts.slice(mid).join('，')]
    }
  }
  const rise = sentences[0] || person.story
  const rest = sentences.slice(1).join('。') || rise

  return {
    eiModule: `${closeSentence(rise)}${closeSentence(lens.ei)}给你的建议：${closeSentence(pack[2])}`,
    snModule: `${closeSentence(rest)}${closeSentence(lens.sn)}给你的建议：${closeSentence(pack[3])}`,
    tfModule: `${closeSentence(pack[0])}${closeSentence(lens.tf)}给你的建议：${closeSentence(pack[4])}`,
    pjModule: `${closeSentence(pack[1])}${closeSentence(lens.pj)}给你的建议：${closeSentence(pack[5])}`,
  }
}
