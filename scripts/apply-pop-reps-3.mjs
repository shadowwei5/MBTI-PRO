const src = readFileSync(FILE, 'utf8')
const lines = src.split('\n')
const parse = (l) => [...l.matchAll(/'([^']*)'/g)].map((m) => m[1])
const applied = []

for (const [code, typeName, add, work, drop, dim, sideA, sideB, hook, conf] of PLAN) {
  const idx = lines.findIndex((l) => l.trimStart().startsWith(`${code}: [`))
  if (idx < 0) throw new Error(`找不到 ${code} 的名单行`)
  const list = parse(lines[idx])
  if (list.includes(add)) { applied.push({ code, typeName, add, work, drop, dim, sideA, sideB, hook, conf, skip: true }); continue }
  if (drop && !list.includes(drop)) throw new Error(`${code} 名单里没有「${drop}」，实际：${list.join('、')}`)
  if (!drop && list.length >= 4) throw new Error(`${code} 已满 4 位，需要指定换掉谁`)

  const next = drop ? list.map((n) => (n === drop ? add : n)) : [...list]
  if (!drop) next.splice(1, 0, add)
  else {
    const at = next.indexOf(add)
    next.splice(at, 1)
    next.splice(1, 0, add)
  }
  lines[idx] = `  ${code}: [${next.map((n) => `'${n}'`).join(', ')}],`
  applied.push({ code, typeName, add, work, drop, dim, sideA, sideB, hook, conf, before: list, after: next })
}

if (!DRY) writeFileSync(FILE, lines.join('\n'), 'utf8')

